# Step 1 Import Libraries

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

print("Libraries imported")

# Step 2 Load Dataset

df = pd.read_csv('loan_data.csv')

print("Dataset Loaded Successfully")
print(df.head())

# Step 3 Dataset Information

print("First Five Rows:")
print(df.head())

print("Shape (rows, columns):", df.shape)

print("Column Names:", df.columns)

print("Data Types and Non-Null Counts:")
df.info()

print("Statistical Summary:")
print(df.describe())

print("Missing Values:")
print(df.isnull().sum())

print("Duplicate Rows:")
print(df.duplicated().sum())

## Step 4 Check Data Quality

print("Missing Values:")
print(df.isnull().sum())

print("Duplicate Rows:")
print(df.duplicated().sum())

print("Loan Status Distribution:")
print(df["loan_status"].value_counts())

# Step 5 Data Visualization

# 1. Scatter Plot

plt.figure(figsize=(8,5))

sns.scatterplot(
    data=df,
    x="person_income",
    y="loan_amnt",
    hue="loan_status"
)

plt.title("Person Income vs Loan Amount")
plt.xlabel("Person Income")
plt.ylabel("Loan Amount")
plt.grid(True)
plt.show()


# 2. Loan Status Distribution

plt.figure(figsize=(6,4))

sns.countplot(
    data=df,
    x="loan_status"
)

plt.title("Loan Status Distribution")
plt.xlabel("Loan Status")
plt.ylabel("Count")
plt.show()

# Step 6 Separate Features and Target

# Correct syntax: pass columns to drop as a list. Also, make sure to drop the target column 'loan_status' from X.
X = df.drop(columns=["person_age", "person_income", "credit_score", "loan_status"])

y = df["loan_status"]

print("Features:")
print(X.head())

print("Target:")
print(y.head())

print("Features Shape:", X.shape)
print("Target Shape:", y.shape)

# Step 7 Train-Test Split

# Drop rows where target variable y is NaN
non_nan_indices = y.dropna().index
X_clean = X.loc[non_nan_indices]
y_clean = y.loc[non_nan_indices]

X_train, X_test, y_train, y_test = train_test_split(
    X_clean,
    y_clean,
    test_size=0.25,
    random_state=42,
    stratify=y_clean
)

print("X_train Shape:", X_train.shape)
print("X_test Shape:", X_test.shape)

print("y_train Shape:", y_train.shape)
print("y_test Shape:", y_test.shape)

# Step 8 Feature Scaling and Model Creation

from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

# Separate Numerical and Categorical Features

numerical_features = X.select_dtypes(include=np.number).columns
categorical_features = X.select_dtypes(exclude=np.number).columns

# Numerical Data Processing

numerical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

# Categorical Data Processing

categorical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

# Combine Both Pipelines

preprocessor = ColumnTransformer([
    ("num", numerical_pipeline, numerical_features),
    ("cat", categorical_pipeline, categorical_features)
])

# Create Model

model = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", LogisticRegression(max_iter=1000))
])

print("Model Created Successfully")

# Step 9 Train Model

model.fit(X_train, y_train)

print("Model Trained Successfully")

# Step 10 Predict Test Data

y_pred = model.predict(X_test)

print("Predicted Values:")
print(y_pred)

print("Actual Values:")
print(y_test.values)

# Step 11 Confusion Matrix

cm = confusion_matrix(y_test, y_pred)

print("Confusion Matrix:")
print(cm)

plt.figure(figsize=(6,4))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues"
)

plt.title("Confusion Matrix")
plt.xlabel("Predicted Values")
plt.ylabel("Actual Values")
plt.show()

# Step 12 Model Evaluation

accuracy = accuracy_score(y_test, y_pred)

precision = precision_score(y_test, y_pred, average="weighted", zero_division=0)

recall = recall_score(y_test, y_pred, average="weighted", zero_division=0)

f1 = f1_score(y_test, y_pred, average="weighted", zero_division=0)

print("Accuracy:", accuracy)
print("Precision:", precision)
print("Recall:", recall)
print("F1 Score:", f1)

print("\nClassification Report:")
print(classification_report(y_test, y_pred, zero_division=0))

# Step 13 Prediction Probability

y_probability = model.predict_proba(X_test)

print("Prediction Probability:")
print(y_probability)

print("Class Labels:")
print(model.classes_)

# Step 14 New Loan Prediction

# Take one sample applicant from test data
new_loan = X_test.iloc[[0]].copy()

# Predict Loan Status
new_prediction = model.predict(new_loan)

print("New Loan Applicant Details:")
print(new_loan)

